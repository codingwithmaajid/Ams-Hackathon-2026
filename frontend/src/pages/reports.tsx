import { useState } from "react";
import { FileText, Mail, Phone } from "lucide-react";

import { useStore, type ReportKind } from "@/store";
import { PageHeader } from "@/components/layout/page-header";
import { Badge } from "@/components/ui/badge";
import {
  Card,
  CardAction,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";

const FILTERS = ["all", "calls", "emails"] as const;

const KIND_ICON: Record<ReportKind, typeof Phone> = {
  call: Phone,
  email: Mail,
};

export default function ReportsPage() {
  const { reports } = useStore();
  const [filter, setFilter] = useState<(typeof FILTERS)[number]>("all");

  const visible = reports.filter((r) =>
    filter === "all"
      ? true
      : filter === "calls"
        ? r.kind === "call"
        : r.kind === "email"
  );

  return (
    <div className="h-full overflow-y-auto">
      <div className="mx-auto flex w-full max-w-4xl flex-col gap-4 p-4 md:gap-6 md:p-6">
        <PageHeader
          title="Reports"
          description="Every call and email the agent completes is filed here automatically."
        />

        <div className="flex gap-1.5">
          {FILTERS.map((f) => (
            <button
              key={f}
              type="button"
              onClick={() => setFilter(f)}
              className={`rounded-full border px-3 py-1.5 text-xs font-medium transition-colors ${
                filter === f
                  ? "border-transparent bg-primary text-primary-foreground"
                  : "border-border bg-card text-muted-foreground hover:text-foreground"
              }`}
            >
              {f}
            </button>
          ))}
        </div>

        <div className="flex flex-col gap-3">
          {visible.map((r) => {
            const Icon = KIND_ICON[r.kind];
            return (
              <Card key={r.id}>
                <CardHeader>
                  <CardTitle>{r.title}</CardTitle>
                  <CardDescription>
                    {r.contact} · {r.at}
                  </CardDescription>
                  <CardAction>
                    <span
                      className={`flex size-8 items-center justify-center rounded-lg ${r.kind === "call" ? "bg-emerald-100 text-emerald-700" : "bg-sky-100 text-sky-700"}`}
                    >
                      <Icon className="size-4" />
                    </span>
                  </CardAction>
                </CardHeader>
                <CardContent className="flex flex-col gap-2">
                  <p className="text-sm leading-relaxed">{r.summary}</p>
                  <ul className="flex flex-col gap-1.5 border-l-2 border-border pl-3">
                    {r.points.map((p) => (
                      <li
                        key={p}
                        className="text-sm leading-relaxed text-muted-foreground"
                      >
                        {p}
                      </li>
                    ))}
                  </ul>
                </CardContent>
              </Card>
            );
          })}
          {visible.length === 0 && (
            <Card className="items-center py-12">
              <FileText className="size-8 text-muted-foreground/50" />
              <p className="text-sm text-muted-foreground">
                No reports yet — dispatch a call or email first.
              </p>
            </Card>
          )}
        </div>

        <p className="flex items-center gap-2 text-xs text-muted-foreground">
          <Badge variant="outline">auto-filed</Badge>
          Reports are generated by the agent after each completed touchpoint.
        </p>
      </div>
    </div>
  );
}
